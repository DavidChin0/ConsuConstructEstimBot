def structural_group(row):
    category = row.get("category", "")
    keynote = row.get("keynote", "")
    if keynote.startswith("03 31 00"):
        return ("S-ConcretoEstructural", "Concreto estructural", "AUTO",
                "Elemento estructural de concreto amarrado por CSI 03 31 00.x.")
    if keynote.startswith("03 31 01") or keynote.startswith("03 31 02"):
        return ("S-CimentacionConcreto", "Cimentación estructural de concreto", "AUTO",
                "Cimentación estructural amarrada por CSI 03 31 01/02.")
    if keynote.startswith("03 11"):
        return ("S-Encofrado", "Encofrado estructural", "AUTO",
                "Amarre por CSI de encofrado.")
    if keynote.startswith("03 22"):
        return ("S-Refuerzo", "Refuerzo estructural", "AUTO",
                "Amarre por CSI de refuerzo estructural.")
    if keynote.startswith("05 31 13") or keynote.startswith("05 31 23"):
        return ("S-AceroLiviano", "Acero estructural liviano / galvanizado", "AUTO",
                "Amarre por CSI de acero liviano / canaletas / framing.")
    if keynote.startswith("05 20") or keynote.startswith("05 10"):
        return ("S-AceroPesado", "Acero estructural pesado", "AUTO",
                "Amarre por CSI de acero estructural pesado.")
    if category == "Sistemas de vigas estructurales":
        return ("S-SistemaVigas", "Sistema de vigas estructurales", "AUTO",
                "Amarre por categoría estructural específica.")
    return ("S-REVIEW", "Review manual", "REVIEW",
            "No hay firma CSI suficiente para amarrar este estructural automáticamente.")


def wall_rows():
    rows = read_csv(WALL_CSV)
    out = []
    for row in rows:
        out.append(OrderedDict([
            ("category", "Muros"),
            ("correlation_group", row.get("abc_group", "")),
            ("use_scope", row.get("use_scope", "")),
            ("source_type_id", row.get("parent_type_id", "")),
            ("source_type_name", row.get("parent_type_name", "")),
            ("type_mark", row.get("type_mark", "")),
            ("type_keynote", row.get("type_keynote", "")),
            ("type_status", row.get("type_status", "")),
            ("primary_material", row.get("structure_material", "")),
            ("primary_csi", row.get("structure_csi", "")),
            ("material_signature", row.get("layer_summary", "")),
            ("keynote_signature", ""),
            ("blocking_red_layers", row.get("blocking_red_layers", "0")),
            ("nonblocking_red_layers", row.get("nonblocking_red_layers", "0")),
            ("decision", "AUTO"),
            ("confidence", "high"),
            ("rationale", "Correlación de muros ya validada previamente por materiales y CSI."),
        ]))
    return out


def complex_rows(path, category_name, classifier):
    rows = read_csv(path)
    out = []
    for row in rows:
        fns = split_pipe(row.get("layer_functions", ""))
        mats = split_pipe(row.get("layer_materials", ""))
        csis = split_pipe(row.get("layer_material_keynotes", ""))
        pairs = zipped_pairs(fns, mats, csis)
        group, scope, decision, rationale = classifier(pairs)
        blocking, nonblocking = count_red_layers(row)
        primary_material = ""
        primary_csi = ""
        for fn, mat, csi in pairs:
            if fn.lower().startswith("structure"):
                primary_material = mat
                primary_csi = csi
                break
        if not primary_material and pairs:
            primary_material = pairs[0][1]
            primary_csi = pairs[0][2]

        confidence = "high" if decision == "AUTO" and blocking == 0 else ("medium" if decision == "AUTO" else "low")
        out.append(OrderedDict([
            ("category", category_name),
            ("correlation_group", group),
            ("use_scope", scope),
            ("source_type_id", row.get("parent_type_id", "")),
            ("source_type_name", row.get("parent_type_name", "")),
            ("type_mark", row.get("type_mark", "")),
            ("type_keynote", row.get("type_keynote", "")),
            ("type_status", row.get("type_status", "")),
            ("primary_material", primary_material),
            ("primary_csi", primary_csi),
            ("material_signature", material_signature_from_row(row)),
            ("keynote_signature", keynote_signature_from_row(row)),
            ("blocking_red_layers", str(blocking)),
            ("nonblocking_red_layers", str(nonblocking)),
            ("decision", decision),
            ("confidence", confidence),
            ("rationale", rationale),
        ]))
    return out


def structural_rows():
    rows = read_csv(STRUCTURAL_CSV)
    out = []
    for row in rows:
        group, scope, decision, rationale = structural_group(row)
        confidence = "high" if decision == "AUTO" else "low"
        out.append(OrderedDict([
            ("category", row.get("category", "")),
            ("correlation_group", group),
            ("use_scope", scope),
            ("source_type_id", row.get("element_id", "")),
            ("source_type_name", row.get("type", "")),
            ("type_mark", row.get("type_mark", "")),
            ("type_keynote", row.get("keynote", "")),
            ("type_status", row.get("status", "")),
            ("primary_material", row.get("family", "")),
            ("primary_csi", row.get("keynote", "")),
            ("material_signature", row.get("family", "")),
            ("keynote_signature", row.get("keynote_text", "")),
            ("blocking_red_layers", "0"),
            ("nonblocking_red_layers", "0"),
            ("decision", decision),
            ("confidence", confidence),
            ("rationale", rationale),
        ]))
    return out


def write_csv(path, rows):
    if not rows:
        return
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def build():
    rows_walls = wall_rows()
    rows_floors = complex_rows(FLOOR_CSV, "Suelos", floor_group)
    rows_roofs = complex_rows(ROOF_CSV, "Cubiertas", roof_group)
    rows_ceilings = complex_rows(CEILING_CSV, "Techos", ceiling_group)
    rows_structural = structural_rows()
    all_rows = rows_walls + rows_floors + rows_roofs + rows_ceilings + rows_structural

    write_csv(os.path.join(OUT_DIR, "template_floor_correlation_{}.csv".format(STAMP)), rows_floors)
    write_csv(os.path.join(OUT_DIR, "template_roof_correlation_{}.csv".format(STAMP)), rows_roofs)
    write_csv(os.path.join(OUT_DIR, "template_ceiling_correlation_{}.csv".format(STAMP)), rows_ceilings)
    write_csv(os.path.join(OUT_DIR, "template_structural_correlation_{}.csv".format(STAMP)), rows_structural)
    write_csv(os.path.join(OUT_DIR, "template_complex_correlation_all_{}.csv".format(STAMP)), all_rows)

    print("Walls:", len(rows_walls))
    print("Floors:", len(rows_floors))
    print("Roofs:", len(rows_roofs))
    print("Ceilings:", len(rows_ceilings))
    print("Structural:", len(rows_structural))
    print("All:", len(all_rows))


if __name__ == "__main__":
    build()
