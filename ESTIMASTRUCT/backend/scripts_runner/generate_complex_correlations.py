def read_csv(path):
    with open(path, encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def split_pipe(value):
    if not value:
        return []
    return [part.strip() for part in str(value).split("|") if part.strip()]


def zipped_pairs(functions, materials, keynotes):
    out = []
    for idx, fn in enumerate(functions):
        mat = materials[idx] if idx < len(materials) else ""
        csi = keynotes[idx] if idx < len(keynotes) else ""
        out.append((fn, mat, csi))
    return out


def classify_nonblocking_red(material_name):
    low = (material_name or "").strip().lower()
    if not low:
        return True
    return low in {"cc-none", "air", "default"}


def count_red_layers(row):
    red_materials = split_pipe(row.get("red_layer_materials", ""))
    blocking = 0
    nonblocking = 0
    for material in red_materials:
        if classify_nonblocking_red(material):
            nonblocking += 1
        else:
            blocking += 1
    return blocking, nonblocking


def material_signature_from_row(row):
    return row.get("layer_material_signature", "") or ""


def keynote_signature_from_row(row):
    return row.get("layer_keynote_signature", "") or ""


