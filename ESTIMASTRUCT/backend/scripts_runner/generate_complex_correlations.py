"""Generate unified correlation dictionaries for complex elements based on
layer materials + CSI codes.

Input artifacts already generated by the MCP audit pipeline:
  - complex selector CSVs (walls/floors/roofs/ceilings)
  - structural base selector CSV
  - existing wall correlation CSV

Output:
  - unified all-category correlation CSV
  - per-category correlation CSVs

This does NOT create a second audit source of truth.
It derives reusable correlation contracts from the canonical audit outputs.
"""
